#' Render a Deadwood Structure Output Table in PDF Format
#'
#' Transform a deadwood structure output table as generated by
#' \code{\link{structure_deadwood_output_table}} into a pdf file that can be
#' exported or displayed.
#'
#' The user must make sure that the input object \code{x} has been generated
#' with \code{\link{structure_deadwood_output_table}}, because the function
#' does not check that. For other objects the function will either produce an
#' error or at least strange results.
#'
#' @param x Input object, must be a deadwood structure output table as generated
#'   with \code{\link{structure_deadwood_output_table}}.
#'
#' @param tab_title Character, used for the table title and the file name.
#'
#' @param output_dir Path to the directory where the pdf file will be stored.
#'   Default is \code{NA}; in this case, the file will be written into the
#'   temporary directory of the current R session.
#'
#' @param meta Optional named list with inventory meta-information to display
#'   above the table. Recognised names: \code{year} (inventory year, integer),
#'   \code{area_ha} (total area in ha, numeric), \code{n_plots} (number of
#'   inventory points, integer). Any or all elements may be omitted or
#'   \code{NULL}. When \code{meta} is \code{NULL} (default) no meta block is
#'   rendered.
#'
#' @param language Language of the rendered output. Currently only
#'   \code{"ger"} (German) is implemented and accepted; passing any
#'   other value raises an error. Future languages will be added as
#'   separate template files (one template per language, keeping each
#'   template linguistically consistent).
#'
#' Deliberately not a member of the pdf_output family: deadwood evaluation is a
#' post-CRAN feature, so this function must not appear in the cross-links of the
#' user-facing PDF functions.
#'
#' @return The path to the rendered pdf file.
#'
#' @keywords internal
#'
#'
structure_deadwood_output_table_pdf <- function(x,
                                                tab_title,
                                                output_dir = NA,
                                                meta = NULL,
                                                language = c("ger")) {

  language <- match.arg(language)
  check_pdf_dependencies("structure_deadwood_output_table_pdf")

  # pre-process input
  if(is.na(output_dir)) output_dir <- tempdir()
  # Absolute path so the PDF lands where the caller expects.
  output_dir <- normalizePath(output_dir, winslash = "/",
                              mustWork = FALSE)
  tab_title      <- as.character(tab_title)


  # Render the table in pdf format and hand back the file path
  path <- rmarkdown::render(
    input = paste0(system.file(package = "FeNEU"),
                   "/rmd/output_deadwood_structure_table.Rmd"
    ),
    params        = list(x         = x,
                         tab_title = tab_title,
                         meta      = meta
    ),
    output_format = "pdf_document",
    output_file   = paste0("output_deadwood_structure_table_ger_",
                           tab_title,
                           ".pdf"),
    output_dir    = output_dir
  )

  path



}
