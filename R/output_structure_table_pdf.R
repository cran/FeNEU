#' Render an Output Structure Table in PDF Format
#'
#' Transform an inventory output structure table as generated by
#' \code{\link{output_structure_table}} into a pdf file that can be exported or
#' displayed.
#'
#' The user must make sure that the input object x has been generated with
#' \code{\link{output_structure_table}}, because the function does not check that.
#' For other objects the function will either produce an error or at least
#' strange results.
#'
#' The file name is assembled as
#' \code{output_structure_table_ger_<tab_title>_<type>_<cohort>.pdf}. The
#' \code{<cohort>} tag identifies the tree cohort the table represents and is
#' taken from the tag the \code{structure_table_*()} functions attach to their
#' result (\code{"mainstand"} for the \code{*_main_stand()} functions,
#' \code{"alllayers"} for the general functions called with their default
#' \code{tree_filter}, or a sanitised form of a custom \code{tree_filter}
#' expression). This keeps the four standard variants (main stand / all layers
#' \eqn{\times} age / diameter classes) in separate, self-describing files
#' instead of overwriting one another.
#'
#' The class axis (\code{<type>}, age or dq) is likewise read off the object
#' (the \code{class_type} attribute stamped by
#' \code{\link{output_structure_table}}), and the same cohort tag also selects
#' the disclaimer note (main-stand note, all-layers note, or - for a custom
#' \code{tree_filter} - a plain "Benutzerdefinierte Auswahl" subtitle without a
#' note). Neither is a function argument any longer, so they can no longer be
#' set inconsistently with the actual table content.
#'
#' @param x Input object, must be an output structure table as generated with
#'   \code{\link{output_structure_table}}
#'
#' @param tab_title Character, used for the table title and the file name.
#'
#' @param output_dir Path to the directory where the information sheet will
#'   be stored in. Default is NA; in this case, the file will be written into
#'   the temporary directory of the current R session. This directory will,
#'   however, only available as long as the session is going on.
#'
#' @param meta Optional named list with inventory meta-information to display
#'   above the table. Recognised names: \code{year} (inventory year, integer),
#'   \code{area_ha} (total area in ha, numeric), \code{n_plots} (number of
#'   inventory points, integer). Any or all elements may be omitted or
#'   \code{NULL}. When \code{meta} is \code{NULL} (default) no meta block is
#'   rendered - unless \code{inventory} is supplied (see below).
#'
#' @param inventory Optional \code{\link{fe_inventory}} object. A convenience
#'   shortcut for the \code{meta} block: when \code{meta} is \code{NULL} and
#'   \code{inventory} is given, the meta list is derived automatically via
#'   \code{\link{inventory_meta}}. An explicit \code{meta} always takes
#'   precedence. Supplying \code{inventory} additionally guards against
#'   nonsensical output: structure tables are only meaningful for sample
#'   (concentric-circle) inventories, so a standwise / stand-level inventory
#'   (any plot that is not an \code{fe_ccircle_spatial}) is rejected with a
#'   clear error.
#'
#' @param language Language of the rendered output. Currently only
#'   \code{"ger"} (German) is implemented and accepted; passing any
#'   other value raises an error. Future languages will be added as
#'   separate template files (one template per language, keeping each
#'   template linguistically consistent).
#'
#' @family pdf_output
#'
#' @seealso The stages that produce this function's input:
#'   \code{\link{output_structure_table}}, fed by one of the four structure
#'   tables \code{\link{structure_table_age_class}},
#'   \code{\link{structure_table_age_class_main_stand}},
#'   \code{\link{structure_table_d_q_class}}, and
#'   \code{\link{structure_table_d_q_class_main_stand}}. The base-table
#'   counterpart of this function is \code{\link{output_base_table_pdf}}.
#'
#' @return The path to the rendered pdf file
#'
#' @export
#'
#' @examples
#' \donttest{
#' # Build the table (the species cast warnings are a natural side effect of
#' # the required species grouping)
#' structure_tab <- data_ex3_sample_trees_essentials |>
#'   structure_table_age_class_main_stand() |>
#'   output_structure_table()
#'
#' # Render it; output_dir defaults to tempdir(), which is what we want here
#' pdf_path <- output_structure_table_pdf(structure_tab, "example_ex3")
#' basename(pdf_path)
#' }
output_structure_table_pdf <- function(x,
                                  tab_title,
                                  output_dir = NA,
                                  meta = NULL,
                                  inventory = NULL,
                                  language = c("ger")) {

  language <- match.arg(language)

  # Structure tables are only meaningful for sample inventories (concentric
  # circles). When the source inventory is supplied, use it to refuse a
  # standwise / stand-level inventory (any plot that is not an
  # fe_ccircle_spatial) rather than render a nonsensical table. Runs before the
  # toolchain check so bad input fails fast regardless of the PDF setup. This is
  # the cheap guard; it only fires when `inventory` is passed - an airtight,
  # always-on guard would need the inventory type stamped onto the table object
  # (a post-CRAN attribute-threading follow-up, see CLAUDE.md).
  if (!is.null(inventory)) {
    stopifnot(is_fe_inventory(inventory))
    if (!all(vapply(inventory$plot,
                    ForestElementsR::is_fe_ccircle_spatial, logical(1)))) {
      stop(fe_msg("structure_table_not_sample"), call. = FALSE)
    }
  }

  check_pdf_dependencies("output_structure_table_pdf")

  # Convenience: derive the meta block automatically from the source inventory
  # when the caller hands over the fe_inventory instead of a ready-made meta
  # list. An explicit meta always wins.
  if (is.null(meta) && !is.null(inventory)) meta <- inventory_meta(inventory)

  # The class axis (age / dq) and the tree cohort are read off the object
  # itself - stamped by output_structure_table() - so neither has to be (and can
  # no longer be mis-)specified by the caller.
  m <- .table_pdf_meta(x, "output_structure_table_pdf")

  # pre-process input
  if(is.na(output_dir)) output_dir <- tempdir()
  # Absolute output_dir so PDFs do not end up next to the template
  # inside the installed FeNEU/rmd/ directory -- rmarkdown::render
  # resolves output_file relative to the input template otherwise.
  output_dir <- normalizePath(output_dir, winslash = "/",
                              mustWork = FALSE)
  tab_title      <- as.character(tab_title)


  # Render the table in pdf format and hand back the file path
  path <- rmarkdown::render(
    input = paste0(system.file(package = "FeNEU"),
                   "/rmd/output_structure_table_template_ger.Rmd"
    ),
    params        = list(x         = x,
                         tab_title = tab_title,
                         type      = m$type,
                         meta      = meta,
                         cohort    = m$cohort
    ),
    output_format = "pdf_document",
    output_file   = paste0("output_structure_table_ger_",
                           .safe_filename_part(tab_title), "_",
                           m$type, "_", m$file_tag,
                           ".pdf"),
    output_dir    = output_dir
  )

  path
}
